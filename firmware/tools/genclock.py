"""Bake a big clock face (digits + colon only) into a TFT_eSPI VLW flash array.

The hero clock only ever renders "HH:MM", so we bake just space, 0-9 and ':' at a
large size -> a tiny header. Arial Bold is a neutral grotesque, ~identical to
NotoSans Bold for digits, so it matches the labels. Re-run with a different SIZE
to make the clock bigger/smaller. Output: src/ClockFont.h (array `ClockFont`).

VLW format (big-endian int32), per TFT_eSPI Extensions/Smooth_font.cpp:
  header: gCount, version(11), fontSize, 0, ascent, descent
  per glyph (28B): unicode, height, width, xAdvance, gdY(=ascent-top), gdX(=left)
  then 8-bit alpha bitmaps (width*height each), row-major.
"""
import struct
from PIL import Image, ImageDraw, ImageFont

TTF  = r"C:\Windows\Fonts\arialbd.ttf"   # Arial Bold (neutral, ~= NotoSans Bold)
SIZE = 60
NAME = "ClockFont"
OUT  = r"C:\Users\marco\Desktop\smart-alarm\firmware\src\ClockFont.h"
CPS  = [0x20] + list(range(0x30, 0x3A)) + [0x3A]   # space, 0-9, ':'

font = ImageFont.truetype(TTF, SIZE)
asc_real, _ = font.getmetrics()

# First pass: rasterise each glyph and record its metrics.
glyphs = []  # (cp, w, h, adv, gdY, gdX, bitmap)
for cp in CPS:
    ch = chr(cp)
    l, t, r, b = font.getbbox(ch) or (0, 0, 0, 0)
    w, h = max(0, r - l), max(0, b - t)
    adv = round(font.getlength(ch))
    if w and h:
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255)
        glyphs.append((cp, w, h, adv, asc_real - t, l, img.tobytes()))
    else:
        glyphs.append((cp, 0, 0, adv, 0, 0, b""))

# Tight header metrics: bound the band to the glyphs that actually exist (digits
# have no leading/descenders), so the clock sprite is no taller than the digits
# and neighbouring labels can sit right against it without being overwritten.
asc  = max((g[4] for g in glyphs if g[2] > 0), default=asc_real)        # max gdY
desc = max([g[2] - g[4] for g in glyphs if g[2] > 0] + [0])            # max (h - gdY)

metrics, bitmaps = bytearray(), bytearray()
for cp, w, h, adv, gdY, gdX, bm in glyphs:
    for v in (cp, h, w, adv, gdY, gdX, 0):
        metrics += struct.pack(">i", v)
    bitmaps += bm
blob = struct.pack(">6i", len(CPS), 11, SIZE, 0, asc, desc) + bytes(metrics) + bytes(bitmaps)
ascent, descent = asc, desc

lines = [f"// Arial Bold baked to a TFT_eSPI VLW at {SIZE}px - clock digits + ':' only.",
         f"// {len(CPS)} glyphs, {len(blob)} bytes. Generated by tools/genclock.py.",
         f"const uint8_t {NAME}[] PROGMEM = {{"]
for i in range(0, len(blob), 16):
    lines.append("  " + "".join(f"0x{c:02X}, " for c in blob[i:i + 16]).rstrip())
lines.append("};\n")
open(OUT, "w", encoding="ascii").write("\n".join(lines))
print(f"{OUT}: {len(CPS)} glyphs, {len(blob)} bytes, ascent {ascent} descent {descent}")
